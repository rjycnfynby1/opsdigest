def is_obscene(w: str) -> bool:
    """Есть ли в слове матерный корень (слово уже нормализовано: строчные, ё→е, латиница→кириллица)."""
    if not w or w in SAFE or w.startswith(SAFE_PREFIX):
        return False
    if "пизд" in w or "залуп" in w or "гандон" in w or "гондон" in w or "шлюх" in w or "дроч" in w:
        return True
    if re.search(r"ху[йяеию]", w) and "страх" not in w:
        return True
    if re.search(r"(?:^|на|по|ни|за|до)хер(?!ес|сон|увим)", w):
        return True
    if _EB.match(w) or re.search(r"(?:долбо|долба|мозго)еб", w):
        return True
    if w.startswith("бля") or w.startswith("муд") or w.startswith(("пидор", "пидар", "пидр", "манд")):
        return True
    if "говн" in w or "дерьм" in w or "жоп" in w:
        return True
    return False


def _normalize(tok: str) -> str:
    t = tok.lower()
    if re.fullmatch(r"[a-z]+", t):
        return LATIN.get(t, "")
    if re.search(r"[а-яё]", t):
        t = t.translate(_LOOK)
    return t.replace("ё", "е")


def _variants(norm: str) -> list[str]:
    """Звёздочки вместо букв: х*й, п**дец → подставить буквы."""
    if "*" not in norm or norm.count("*") > 3:
        return [norm]
    out = [""]
    for ch in norm:
        if ch == "*":
            out = [o + c for o in out for c in ("и", "у", "е", "а", "о", "я", "")]
        else:
            out = [o + ch for o in out]
    return out[:400]


def _with_case(src: str, dst: str) -> str:
    if not dst or dst.startswith("["):
        return dst
    if src[:1].isupper():
        return dst[:1].upper() + dst[1:]
    return dst


def _replace_word(tok: str, text: str, start: int, end: int) -> str | None:
    """Замена для одного слова или None (не грубое)."""
    norm = _normalize(tok)
    if not norm:
        return None
    for v in _variants(norm):
        if v in LEX:
            rep = LEX[v]
            if v in ("сука", "блядь", "блять", "суки") and _interjection(text, start, end):
                rep = DELETE
            elif v in TUPOY and re.search(r"(?:\b(?:ты|вы|он|она|они|я|мы)|Ч\d+)\s*(?:—|-|такой|такая|такие)?\s*$",
                                         text[max(0, start - 20):start]):
                rep = TUPOY[v]
            return _with_case(tok, rep)
    if any(is_obscene(v) for v in _variants(norm)):
        return MARK
    return None


def _interjection(text: str, start: int, end: int) -> bool:
    """«сука, опять упало» / «…, блядь.» — междометие, а не оскорбление."""
    before = text[max(0, start - 3):start]
    after = text[end:end + 2]
    return bool(re.match(r"\s*[,.!?…]|\s*$", after)) or bool(re.search(r"[,(]\s*$", before)) or start == 0


_SPACED = re.compile(r"(?<![\wА-Яа-яЁё])((?:[А-Яа-яЁёA-Za-z][ .\-_*]){2,}[А-Яа-яЁёA-Za-z])(?![\wА-Яа-яЁё])")
_TOKEN = re.compile(r"[А-Яа-яЁёA-Za-z0-9@$*]*[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z0-9@$*]*")


def soften(text: str) -> str:
    if not text:
        return text
    out = text
    # буквы через пробел/точку: «п и з д е ц»
    def spaced(m: re.Match) -> str:
        joined = re.sub(r"[ .\-_*]", "", m.group(1))
        rep = _replace_word(joined, joined, 0, len(joined))
        return rep if rep is not None else m.group(0)
    out = _SPACED.sub(spaced, out)
    for rx, rep in PHRASES:
        out = rx.sub(rep, out)

    def word(m: re.Match) -> str:
        tok = m.group(0)
        if re.fullmatch(r"[0-9@$*]+", tok) or re.fullmatch(r"(?:Ч|Тел|Почта)\d+", tok):
            return tok
        rep = _replace_word(tok, out, m.start(), m.end())
        return tok if rep is None else rep
    out = _TOKEN.sub(word, out)
    if "который мог бы работать лучше" in out or "которые могли бы работать лучше" in out:
        out = _agree(out)
    if DELETE in out:  # уборка вокруг удалённых слов: «бля, опять упало» → «опять упало»
        out = re.sub(r"(?m)(^|[:⏎][ \t]*)[ \t]*\x00[ \t]*,?[ \t]*", r"\1", out)
        out = re.sub(r",?[ \t]*\x00[ \t]*(?=[,.!?…)])", "", out)
        out = re.sub(r"[ \t]*\x00[ \t]*,?", " ", out)
        out = re.sub(r"(?<=\S) {2,}(?=\S)", " ", out)
        out = out.replace("\x00", "")
    return out


_DEM = {"эта": "этот", "эту": "этого", "этой": None, "такая": "такой", "такую": "такого", "такой": None,
        "какая": "какой", "какую": "какого", "твоя": "твой", "твою": "твоего"}
_DEM_OBL = {"этой": {"человека": "этого", "человеку": "этому", "человеком": "этим", "человеке": "этом"},
            "такой": {"человека": "такого", "человеку": "такому", "человеком": "таким", "человеке": "таком"},
            "какой": {"человека": "какого", "человеку": "какому", "человеком": "каким", "человеке": "каком"}}


def _agree(out: str) -> str:
    """«эта человек, который…» → «этот человек, который…», запятая после оборота."""
    def dem(m: re.Match) -> str:
        w, noun = m.group(1), m.group(2)
        low = w.lower()
        if low in _DEM_OBL:
            rep = _DEM_OBL[low].get(noun)
        else:
            rep = _DEM.get(low)
        if not rep:
            return m.group(0)
        rep = rep[:1].upper() + rep[1:] if w[:1].isupper() else rep
        return f"{rep} {noun}"
    out = re.sub(r"\b(эта|эту|этой|такая|такую|такой|какая|какую|какой|твоя|твою)\s+(человек[а-я]*)", dem, out,
                 flags=re.I)
    return re.sub(r"(работать лучше)([ \t]+)(?=[А-Яа-яЁёA-Za-z])", r"\1,\2", out)


def has_obscene(text: str) -> bool:
    return any(is_obscene(_normalize(t)) for t in _TOKEN.findall(text or ""))
