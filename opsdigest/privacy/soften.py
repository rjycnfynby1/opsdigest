def _m(nom: str, stem: str | None = None, animate: bool = True) -> dict[str, str]:
    """Мужской род на согласную (мудак, придурок → придурк-, долбоёб)."""
    st = stem or nom
    last = st[-1]
    pl = "и" if last in _VS else "ы"
    pgen = "ей" if last in "жшчщ" else "ов"
    f = {"nom": nom, "gen": st + "а", "dat": st + "у", "acc": st + "а" if animate else nom,
         "ins": st + ("ем" if last in _SIB else "ом"), "pre": st + "е", "pnom": st + pl, "pgen": st + pgen,
         "pdat": st + "ам", "pacc": st + pgen if animate else st + pl, "pins": st + "ами", "ppre": st + "ах"}
    return f


def _a(nom: str, animate: bool = True) -> dict[str, str]:
    """На -а/-я (сука, дура, хуйня, мудила)."""
    st, end = nom[:-1], nom[-1]
    last = st[-1]
    soft = end == "я"
    gen = st + ("и" if soft or last in _VS or last in "жшчщ" else "ы")
    ins = st + ("ей" if soft or last in _SIB else "ой")
    pgen = st + ("ь" if soft and last not in "аеиоуы" else "")
    return {"nom": nom, "gen": gen, "dat": st + "е", "acc": st + ("ю" if soft else "у"), "ins": ins,
            "pre": st + "е", "pnom": gen, "pgen": pgen if animate else pgen, "pdat": st + ("ям" if soft else "ам"),
            "pacc": pgen if animate else gen, "pins": st + ("ями" if soft else "ами"), "ppre": st + ("ях" if soft else "ах")}


def _f_soft(nom: str) -> dict[str, str]:
    """Женский на -ь (мразь, тварь)."""
    st = nom[:-1]
    return {"nom": nom, "gen": st + "и", "dat": st + "и", "acc": nom, "ins": st + "ью", "pre": st + "и",
            "pnom": st + "и", "pgen": st + "ей", "pdat": st + "ям", "pacc": st + "ей", "pins": st + "ями",
            "ppre": st + "ях"}


def _n(nom: str) -> dict[str, str]:
    """Средний на -о/-е (говно, дерьмо, безобразие, разгильдяйство)."""
    st, end = nom[:-1], nom[-1]
    if nom.endswith("ие"):
        st = nom[:-1]
        return {"nom": nom, "gen": st + "я", "dat": st + "ю", "acc": nom, "ins": st + "ем", "pre": st + "и",
                "pnom": st + "я", "pgen": st[:-1] + "ий", "pdat": st + "ям", "pacc": st + "я", "pins": st + "ями",
                "ppre": st + "ях"}
    return {"nom": nom, "gen": st + "а", "dat": st + "у", "acc": nom, "ins": st + ("ом" if end == "о" else "ем"),
            "pre": st + "е", "pnom": st + "а", "pgen": st, "pdat": st + "ам", "pacc": st + "а", "pins": st + "ами",
            "ppre": st + "ах"}


def _adj(stem: str, kind: str = "hard") -> dict[str, str]:
    """Прилагательное: hard (хуёвый), velar (плохой, мудацкий), soft (ебучий)."""
    if kind == "soft":
        e = {"m": "ий", "f": "ая", "n": "ее", "pl": "ие", "gen": "его", "dat": "ему", "ins": "им", "pre": "ем",
             "facc": "ую", "fobl": "ей", "pgen": "их", "pins": "ими"}
    elif kind == "velar":
        e = {"m": "ий", "f": "ая", "n": "ое", "pl": "ие", "gen": "ого", "dat": "ому", "ins": "им", "pre": "ом",
             "facc": "ую", "fobl": "ой", "pgen": "их", "pins": "ими"}
    elif kind == "stressed":  # плохой
        e = {"m": "ой", "f": "ая", "n": "ое", "pl": "ие", "gen": "ого", "dat": "ому", "ins": "им", "pre": "ом",
             "facc": "ую", "fobl": "ой", "pgen": "их", "pins": "ими"}
    else:
        e = {"m": "ый", "f": "ая", "n": "ое", "pl": "ые", "gen": "ого", "dat": "ому", "ins": "ым", "pre": "ом",
             "facc": "ую", "fobl": "ой", "pgen": "ых", "pins": "ыми"}
    return {k: stem + v for k, v in e.items()}


def _pair(src: dict[str, str], dst: dict[str, str]) -> dict[str, str]:
    out: dict[str, str] = {}
    for k, v in src.items():
        out.setdefault(_norm(v), dst.get(k) or dst.get("nom") or dst.get("m"))
    return out


def _norm(s: str) -> str:
    return s.lower().replace("ё", "е")


