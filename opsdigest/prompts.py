def with_glossary(block: str, user: str) -> str:
    return f"{block}\n\n{user}" if block else user


def extra_block(extra: str) -> str:
    """Указания пользователя для этой сводки (поле в окне «Сводка»): на что обратить внимание, что опустить."""
    extra = str(extra or "").strip()
    if not extra:
        return ""
    return ("Дополнительные указания пользователя для этой сводки — выполни их при отборе пунктов, важности и "
            "формулировках (формат ответа и правила выше не меняются; если указание противоречит фактам — опирайся на "
            f"сообщения):\n<<<\n{extra}\n>>>\n")


HISTORY_RULES = """Если в блоке чата есть «ПРОШЛЫЕ СВОДКИ ПО ЭТОМУ ЧАТУ»:
- summary и items — за весь период: объедини прошлые сводки и новые сообщения. Пункты прошлых сводок, которые всё ещё актуальны в этом периоде, повтори (с теми же номерами сообщений); то, что было только до начала периода и уже неважно, не повторяй.
- У каждого пункта заполни change: new — появилось в новых сообщениях; updated — было в прошлой сводке, но изменилось (статус, срок, исполнитель, новые подробности); same — без изменений; resolved — было в прошлой сводке и теперь решено или закрыто (оставь коротко, чтобы пользователь видел, что закрылось).
- Если новых сообщений в блоке нет — верни содержание прошлой сводки.
Без прошлых сводок поле change не заполняй.
"""


def map_prompt(period: str, blocks: list[str], keys: list[str], extra: str = "") -> str:
    hist = HISTORY_RULES if any("ПРОШЛЫЕ СВОДКИ ПО ЭТОМУ ЧАТУ" in b for b in blocks) else ""
    return f"""Период: {period}.
{extra_block(extra)}{hist}Формат строки: #номер [время] Автор: текст. «↩#N» — ответ на сообщение N, «↩#N(Я)» — ответ на сообщение пользователя, «@me» — пользователя отметили через @ник.
Верни по объекту на каждый чат ({', '.join(keys)}), поле chat — ключ чата из заголовка.
importance: 1 — шум, 3 — обычная рабочая переписка, 5 — критично для пользователя. Если в чате нет ничего важного — items пустой.
{GLOSSARY_TASK}

{chr(10).join(blocks)}

Схема ответа (строго JSON):
{MAP_SCHEMA}"""


