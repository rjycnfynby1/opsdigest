def reduce_prompt(period: str, chats_json: str, refs_text: str, top_n: int, extra: str = "", prev: str = "") -> str:
    prev_part = (f"""
{prev}
changes — что изменилось по сравнению с прошлой сводкой: новые важные пункты, изменившиеся статусы аварий и задач,
что закрыто (у пунктов чатов есть change: new | updated | same | resolved). Не больше 10, самое важное первым;
если изменений нет — пустой список.
""" if prev else "\nПрошлой сводки нет — changes пустой список.\n")
    return f"""Период: {period}.
{extra_block(extra)}{prev_part}Ниже — сводки по отдельным чатам (уже обработаны). Собери общую картину для пользователя:
- top — не больше {top_n} пунктов, на что ему нужно отреагировать самому, по убыванию важности. Сначала прямые вопросы к нему (to_me = tag или reply), затем его задачи (owner = me), затем вопросы и задачи в его зоне без исполнителя (owner = nobody), затем аварии в его зоне. Пункты, где к нему обратились только по имени и это может быть тёзка, ставь ниже и пиши в why «возможно, не вам».
- Пункты, которые ведёт другой человек (owner = other), в top не ставь: если за ними стоит проследить (control = true или тема в зоне пользователя) — в control, с тем, кто исполнитель.
- incidents — сбои и аварии; если одна и та же проблема или один номер обсуждается в нескольких чатах, объедини в один пункт.
- competences — что происходит по каждой компетенции пользователя (только если что-то есть).
- Не повторяй одно и то же в разных разделах. Ничего не выдумывай.

Сводки чатов:
{chats_json}

Номера инцидентов и задач, встречающиеся в нескольких местах:
{refs_text or "—"}

Схема ответа (строго JSON):
{REDUCE_SCHEMA}"""


